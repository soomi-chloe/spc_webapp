def calc_unbiased_const(const_name: str, n: int) -> float:
    """
    공정능력 분석용 불편 상수를 계산합니다.

    Parameters
    ----------
    const_name : str
        상수 이름 ('d2', 'd3', 'd4', 'c2', 'c3', 'c4')
    n : int
        부분군 크기 (subgroup size)

    Returns
    -------
    float
        해당 상수 값
    """
    const_name = const_name.lower()

    if const_name == 'd2':
        if n in _D2_TABLE:
            return _D2_TABLE[n]
        elif n >= 51:
            # n >= 51일 때 근사식 사용
            return 3.4873 + 0.0250141 * n - 0.00009823 * n ** 2
        else:
            raise ValueError(f"d2: n={n}은 지원되지 않습니다 (n=2~50 또는 n>=51)")

    elif const_name == 'd3':
        if n in _D3_TABLE:
            return _D3_TABLE[n]
        elif n >= 26:
            # n >= 26일 때 근사식 사용
            return (0.80818
                    - 0.051871 * n
                    + 0.00005098 * n ** 2
                    - 0.00000019 * n ** 3)
        else:
            raise ValueError(f"d3: n={n}은 지원되지 않습니다 (n=2~25 또는 n>=26)")

    elif const_name == 'd4':
        if n in _D4_TABLE:
            return _D4_TABLE[n]
        elif n >= 26:
            # n >= 26일 때 근사식 사용
            return (2.88606
                    + 0.051313 * n
                    - 0.00049243 * n ** 2
                    + 0.00000188 * n ** 3)
        else:
            raise ValueError(f"d4: n={n}은 지원되지 않습니다 (n=2~25 또는 n>=26)")

    elif const_name == 'c2':
        # c2 = (sqrt(2)/sqrt(n)) * (Γ(n/2) / Γ((n-1)/2))
        return (sqrt(2) / sqrt(n)) * (gamma(n / 2) / gamma((n - 1) / 2))

    elif const_name == 'c3':
        # c3 = sqrt((n-1)/n - c2^2)
        c2 = calc_unbiased_const('c2', n)
        return sqrt((n - 1) / n - c2 ** 2)

    elif const_name == 'c4':
        # c4 = (sqrt(2)/sqrt(n-1)) * (Γ(n/2) / Γ((n-1)/2))
        return (sqrt(2) / sqrt(n - 1)) * (gamma(n / 2) / gamma((n - 1) / 2))

    else:
        raise ValueError(
            f"알 수 없는 상수 이름: '{const_name}'. "
            f"사용 가능: d2, d3, d4, c2, c3, c4"
        )


